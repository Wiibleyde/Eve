-- Create "birthdays" table
CREATE TABLE "birthdays" ("id" bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY, "discord_id" character varying NOT NULL, "birthday" timestamptz NOT NULL, "created_at" timestamptz NOT NULL, "updated_at" timestamptz NOT NULL, PRIMARY KEY ("id"));
-- Create index "birthdays_discord_id_key" to table: "birthdays"
CREATE UNIQUE INDEX "birthdays_discord_id_key" ON "birthdays" ("discord_id");
